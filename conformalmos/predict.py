"""Predict MOS for unlabeled WAV files. Run: python -m conformalmos.predict --help."""
import argparse
import csv
import hashlib
import importlib.util
import json
from pathlib import Path
import numpy as np
import soundfile as sf
import torch
import torchaudio
from .model import PredictionHead
from .calibration import intervals

ROOT = Path(__file__).resolve().parents[1]
M2D_NAME = "m2d_clap_vit_base-80x608p16x16-240128"

def preprocess(path):
    audio, sr = sf.read(path, dtype="float32", always_2d=True)
    if not len(audio) or not np.isfinite(audio).all():
        raise ValueError(f"Empty or nonfinite audio: {path}")
    wave = torch.from_numpy(audio.mean(axis=1))
    if sr != 16000:
        wave = torchaudio.functional.resample(wave, sr, 16000)
    wave = wave[:80000]
    return torch.nn.functional.pad(wave, (0, 80000 - len(wave)))

def digest(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024*1024), b""):
            h.update(chunk)
    return h.hexdigest()

def load_encoder(runtime, weight, device):
    if not runtime.is_file() or not weight.is_file():
        raise FileNotFoundError("M2D runtime/weights missing. Run python scripts/download_m2d.py first.")
    manifest = json.loads((ROOT / "assets/manifest.json").read_text())
    if digest(runtime) != manifest["m2d_runtime"]["sha256"]:
        raise ValueError("M2D runtime checksum mismatch")
    if digest(weight) != manifest["m2d_weights"]["sha256"]:
        raise ValueError("M2D weight checksum mismatch")
    spec = importlib.util.spec_from_file_location("conformalmos_m2d_runtime", runtime)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    encoder = module.PortableM2D(weight_file=str(weight), flat_features=True).to(device).eval()
    for p in encoder.parameters():
        p.requires_grad_(False)
    return encoder

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input", required=True, type=Path, help="WAV file or directory (recursive)")
    ap.add_argument("--output", required=True, type=Path, help="New prediction CSV; existing files are protected")
    ap.add_argument("--checkpoint", type=Path, default=ROOT/"assets/conformalmos_m2d_head.pt")
    ap.add_argument("--m2d-runtime", type=Path, default=ROOT/"external/portable_m2d.py")
    ap.add_argument("--m2d-weight", type=Path, default=ROOT/"external"/M2D_NAME/"checkpoint-300.pth")
    ap.add_argument("--device", choices=["cpu", "cuda"], default="cpu")
    ap.add_argument("--batch-size", type=int, default=8)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--calibration", type=Path, help="JSON generated by conformalmos.calibrate")
    ap.add_argument("--no-intervals", action="store_true")
    args = ap.parse_args(argv)
    if args.batch_size < 1 or args.threads < 1:
        ap.error("batch-size and threads must be positive")
    if args.output.exists() or Path(str(args.output)+".json").exists():
        ap.error("Output already exists; select a new filename")
    files = sorted(p for p in args.input.rglob("*") if p.is_file() and p.suffix.lower()==".wav") if args.input.is_dir() else [args.input]
    if not files or any(not p.is_file() for p in files):
        ap.error("No valid input audio files")
    torch.set_num_threads(args.threads)
    device = torch.device(args.device)
    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    state = checkpoint["head_state"]
    head = PredictionHead(in_dim=state["net.1.weight"].shape[1],
        hidden=state["net.1.weight"].shape[0], num_bins=len(state["bins"]))
    head.load_state_dict(state, strict=True)
    head.to(device).eval()
    calibration = json.loads(args.calibration.read_text()) if args.calibration else None
    if calibration and calibration["checkpoint_sha256"] != digest(args.checkpoint):
        raise ValueError("Calibration belongs to a different prediction checkpoint")
    radius = float(calibration["q_hat"]) if calibration else checkpoint.get("q_hat")
    alpha = calibration["alpha"] if calibration else checkpoint.get("alpha")
    if not args.no_intervals and radius is None:
        raise ValueError("No calibration radius; use --no-intervals or --calibration")
    encoder = load_encoder(args.m2d_runtime, args.m2d_weight, device)
    predictions = []
    with torch.inference_mode():
        for i in range(0, len(files), args.batch_size):
            wave = torch.stack([preprocess(p) for p in files[i:i+args.batch_size]]).to(device)
            predictions.extend(head(encoder.encode_clap_audio(wave)).cpu().tolist())
    if not np.isfinite(predictions).all():
        raise ValueError("Nonfinite predictions")
    bounds = intervals(predictions, radius) if not args.no_intervals else None
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["path", "predicted_mos", "lower", "upper", "nominal_coverage"])
        for i, (path, prediction) in enumerate(zip(files, predictions)):
            writer.writerow([str(path.resolve()), prediction,
                bounds[0][i] if bounds else "", bounds[1][i] if bounds else "",
                1-alpha if bounds else ""])
    metadata = dict(checkpoint_sha256=digest(args.checkpoint),
        m2d_weight_sha256=digest(args.m2d_weight), m2d_runtime_sha256=digest(args.m2d_runtime),
        preprocessing="mono, 16 kHz, first 5 seconds, zero padding", n_files=len(files),
        calibration=calibration or dict(method="historical_checkpoint", q_hat=radius, alpha=alpha),
        warning="Nominal coverage is a calibration setting, not a guarantee on arbitrary user audio.")
    with Path(str(args.output)+".json").open("x") as f:
        json.dump(metadata, f, indent=2)
    print(f"Saved {len(files)} predictions to {args.output}")

if __name__ == "__main__":
    main()
